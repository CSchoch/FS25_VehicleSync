dofile("tests/mocks/engine.lua")
dofile("src/VehicleSyncMath.lua")

local M = VehicleSyncMath

describe("VehicleSyncMath", function()
    describe("clamp / sign / moveTowards", function()
        it("clamps below, inside and above", function()
            assert.equals(1, M.clamp(0, 1, 5))
            assert.equals(3, M.clamp(3, 1, 5))
            assert.equals(5, M.clamp(9, 1, 5))
        end)
        it("returns the sign", function()
            assert.equals(1, M.sign(0.1))
            assert.equals(-1, M.sign(-4))
            assert.equals(0, M.sign(0))
        end)
        it("moves towards a target by at most maxDelta", function()
            assert.equals(1, M.moveTowards(0, 5, 1))
            assert.equals(-1, M.moveTowards(0, -5, 1))
            assert.equals(5, M.moveTowards(4.5, 5, 1))
        end)
    end)

    describe("angles", function()
        it("normalizes into (-pi, pi]", function()
            assert.near(0, M.normalizeAngle(2 * math.pi))
            assert.near(math.pi, M.normalizeAngle(math.pi))
            assert.near(math.pi, M.normalizeAngle(-math.pi))
            assert.near(-math.pi / 2, M.normalizeAngle(3 * math.pi / 2))
            assert.near(math.pi / 2, M.normalizeAngle(-3 * math.pi / 2))
            assert.near(0.5, M.normalizeAngle(0.5 + 4 * math.pi))
        end)
        it("computes headings from direction vectors (0 = +z, +x = pi/2)", function()
            assert.near(0, M.headingFromDirection(0, 1))
            assert.near(math.pi / 2, M.headingFromDirection(1, 0))
            assert.near(-math.pi / 2, M.headingFromDirection(-1, 0))
        end)
        it("computes wrapped heading differences", function()
            assert.near(0.2, M.headingDifference(0.1, 0.3))
            assert.near(0.2, M.headingDifference(math.pi - 0.1, -math.pi + 0.1))
            assert.near(-0.2, M.headingDifference(-math.pi + 0.1, math.pi - 0.1))
        end)
    end)

    describe("frames", function()
        it("round trips world -> local -> world", function()
            local ox, oz, h = 10, -5, 0.7
            local lx, lz = M.worldToLocal(ox, oz, h, 17, 3)
            local wx, wz = M.localToWorld(ox, oz, h, lx, lz)
            assert.near(17, wx)
            assert.near(3, wz)
        end)
        it("uses +x = left and +z = forward like the engine", function()
            -- heading pi/2: forward points to world +x, left (local +x) points to world -z
            local wx, wz = M.localToWorld(0, 0, math.pi / 2, 1, 0)
            assert.near(0, wx)
            assert.near(-1, wz)
            wx, wz = M.localToWorld(0, 0, math.pi / 2, 0, 1)
            assert.near(1, wx)
            assert.near(0, wz)
        end)
        it("matches the engine mock's localToLocal", function()
            local a = TestEngine.createNode(3, 4, 0.3)
            local b = TestEngine.createNode(-2, 1, -1.1)
            local x, _, z = localToLocal(a, b, 0, 0, 0)
            local lx, lz = M.worldToLocal(-2, 1, -1.1, 3, 4)
            assert.near(lx, x)
            assert.near(lz, z)
        end)
    end)

    describe("purePursuitCurvature", function()
        it("is zero straight ahead and at the origin", function()
            assert.equals(0, M.purePursuitCurvature(0, 10))
            assert.equals(0, M.purePursuitCurvature(0, 0))
        end)
        it("is positive (left) for points on the left", function()
            assert.is_greater(0, M.purePursuitCurvature(2, 10))
            assert.is_less(0, M.purePursuitCurvature(-2, 10))
        end)
        it("equals 2x / d^2", function()
            assert.near(2 * 3 / 25, M.purePursuitCurvature(3, 4))
        end)
    end)

    describe("rotTimeToAxisSide", function()
        it("maps positive rotTime (left) to negative axisSide", function()
            assert.near(-0.5, M.rotTimeToAxisSide(0.5, 1, -2, 1))
        end)
        it("maps negative rotTime to positive axisSide using minRotTime", function()
            assert.near(0.25, M.rotTimeToAxisSide(-0.5, 1, -2, 1))
        end)
        it("returns 0 for zero rotTime and for invalid limits", function()
            assert.equals(0, M.rotTimeToAxisSide(0, 1, -1, 1))
            assert.equals(0, M.rotTimeToAxisSide(0.5, 0, -1, 1))
            assert.equals(0, M.rotTimeToAxisSide(-0.5, 1, 0, 1))
            assert.equals(0, M.rotTimeToAxisSide(0.5, nil, nil, nil))
        end)
        it("clamps to [-1, 1]", function()
            assert.equals(-1, M.rotTimeToAxisSide(5, 1, -1, 1))
            assert.equals(1, M.rotTimeToAxisSide(-5, 1, -1, 1))
        end)
        it("inverts for a negative steering direction", function()
            assert.near(0.5, M.rotTimeToAxisSide(0.5, 1, -1, -1))
        end)
        it("is inverted by Drivable:updateVehiclePhysics' mapping", function()
            -- replicate the engine mapping (Drivable.lua updateVehiclePhysics)
            local function engineRotTime(axisSide, maxRot, minRot, steeringDirection)
                axisSide = steeringDirection * axisSide
                if axisSide < 0 then
                    return math.min(-maxRot * axisSide, maxRot)
                end
                return math.max(minRot * axisSide, minRot)
            end
            for _, dir in ipairs({ 1, -1 }) do
                for _, rot in ipairs({ -0.8, -0.2, 0, 0.3, 0.9 }) do
                    local axis = M.rotTimeToAxisSide(rot, 0.9, -0.8, dir)
                    assert.near(rot, engineRotTime(axis, 0.9, -0.8, dir), 1e-9)
                end
            end
        end)
    end)

    describe("distance2D / roundToStep", function()
        it("computes planar distances", function()
            assert.near(5, M.distance2D(0, 0, 3, 4))
        end)
        it("rounds to steps and ignores invalid steps", function()
            assert.near(1.25, M.roundToStep(1.3, 0.25))
            assert.near(-0.5, M.roundToStep(-0.4, 0.25))
            assert.equals(1.3, M.roundToStep(1.3, 0))
            assert.equals(1.3, M.roundToStep(1.3, nil))
        end)
    end)
end)
