local engine = dofile("tests/mocks/engine.lua")
engine.loadMod()
local V = dofile("tests/mocks/vehicles.lua")

local STATE = VehicleSyncController.STATE
local REASON = VehicleSyncController.REASON
local ACTION = VehicleSyncSpec.ACTION

describe("Vehicle Sync events", function()
    before_each(function()
        engine.reset()
        engine.loadTranslations()
        VehicleSyncSettings.reset()
    end)

    it("registers all event classes", function()
        engine.loadMod()
        assert.equals(VehicleSyncRequestEvent, engine.eventClasses.VehicleSyncRequestEvent)
        assert.equals(VehicleSyncStateEvent, engine.eventClasses.VehicleSyncStateEvent)
        assert.equals(VehicleSyncSettingsEvent, engine.eventClasses.VehicleSyncSettingsEvent)
    end)

    describe("VehicleSyncSettingsEvent", function()
        local Event = VehicleSyncSettingsEvent

        local function roundTrip(event, connection)
            local stream = engine.createStream()
            event:writeStream(stream, connection)
            local received = Event.emptyNew()
            received:readStream(stream, connection)
            assert.equals(stream.readPos - 1, #stream.data)
            return received
        end

        local function admin(connection, isAdmin)
            g_currentMission.userManager.users[connection] = { getIsMasterUser = function() return isAdmin end }
        end

        it("carries all values from the server to a client", function()
            VehicleSyncSettings.set("maxSyncSpeed", 22)
            VehicleSyncSettings.set("keepSpeedOnSteering", false)
            local event = Event.new()
            -- the event keeps a copy: later changes are sent with the next event
            VehicleSyncSettings.set("maxSyncSpeed", 30)
            VehicleSyncSettings.reset()
            local received = roundTrip(event, engine.createConnection(true))
            assert.is_false(received.isRequest)
            assert.equals(22, VehicleSyncSettings.values.maxSyncSpeed)
            assert.is_false(VehicleSyncSettings.values.keepSpeedOnSteering)
            assert.equals(22, VehicleSyncSettings.get().maxSyncSpeed)
        end)
        it("ignores values sent by a client", function()
            VehicleSyncSettings.set("maxSyncSpeed", 22)
            local event = Event.new()
            VehicleSyncSettings.reset()
            roundTrip(event, engine.createConnection(false))
            assert.equals(16, VehicleSyncSettings.values.maxSyncSpeed)
        end)
        it("lets an admin step a setting and tells every client", function()
            local connection = engine.createConnection(false)
            admin(connection, true)
            local received = roundTrip(Event.newRequest(VehicleSyncSettings.getIndex("radioRange"), 1), connection)
            assert.is_true(received.isRequest)
            assert.equals(1, received.direction)
            assert.equals(550, VehicleSyncSettings.values.radioRange)
            assert.equals(1, #g_server.broadcasts)
            assert.equals(550, g_server.broadcasts[1].values.radioRange)

            roundTrip(Event.newRequest(VehicleSyncSettings.getIndex("disengageOnCartFull"), -1), connection)
            assert.is_false(VehicleSyncSettings.values.disengageOnCartFull)
            assert.equals(2, #g_server.broadcasts)
        end)
        it("does not broadcast a step that changes nothing", function()
            local connection = engine.createConnection(false)
            admin(connection, true)
            roundTrip(Event.newRequest(VehicleSyncSettings.getIndex("keepSpeedOnSteering"), 1), connection)
            assert.equals(0, #g_server.broadcasts)
        end)
        it("refuses players who are not admins, unknown players and unknown settings", function()
            local player = engine.createConnection(false)
            admin(player, false)
            roundTrip(Event.newRequest(1, 1), player)
            roundTrip(Event.newRequest(1, 1), engine.createConnection(false))
            local admin1 = engine.createConnection(false)
            admin(admin1, true)
            roundTrip(Event.newRequest(15, 1), admin1)
            g_currentMission.userManager = nil
            roundTrip(Event.newRequest(1, 1), admin1)
            assert.equals(16, VehicleSyncSettings.values.maxSyncSpeed)
            assert.equals(0, #g_server.broadcasts)
        end)
        it("never executes requests on clients", function()
            local event = Event.newRequest(1, 1)
            event:run(engine.createConnection(true))
            assert.equals(16, VehicleSyncSettings.values.maxSyncSpeed)
        end)
        it("applies terminal steps on the server at once and sends them from clients", function()
            Event.sendStep("maxSyncSpeed", -1)
            assert.equals(15, VehicleSyncSettings.values.maxSyncSpeed)
            assert.equals(1, #g_server.broadcasts)

            g_server = nil
            Event.sendStep("connectRange", 1)
            Event.sendStep("nope", 1)
            local sent = g_client.serverConnection.sent
            assert.equals(1, #sent)
            assert.is_true(sent[1].isRequest)
            assert.equals(VehicleSyncSettings.getIndex("connectRange"), sent[1].index)
            assert.equals(1, sent[1].direction)
            assert.equals(60, VehicleSyncSettings.values.connectRange)
            assert.has_no_error(function() Event.broadcast() end)
        end)
        it("knows who may change the settings locally", function()
            assert.is_true(Event.getCanChangeLocally())
            g_server = nil
            assert.is_false(Event.getCanChangeLocally())
            g_currentMission.isMasterUser = true
            assert.is_true(Event.getCanChangeLocally())
            g_currentMission = nil
            assert.is_false(Event.getCanChangeLocally())
        end)
        it("sends the values to a joining player only on the server", function()
            local connection = engine.createConnection(false)
            Event.onConnectionFinishedLoading({}, connection)
            assert.equals(1, #connection.sent)
            Event.onConnectionFinishedLoading({}, nil)
            g_server = nil
            Event.onConnectionFinishedLoading({}, connection)
            assert.equals(1, #connection.sent)
        end)
    end)

    describe("VehicleSyncRequestEvent", function()
        it("round trips through a stream and runs on the server", function()
            local leader, follower = V.createScene()
            leader:vsSetNetworkEnabled(true)
            local connection = engine.createConnection(false)
            follower.ownerConnection = connection

            local event = VehicleSyncRequestEvent.new(follower, ACTION.TOGGLE_CONNECT, nil)
            assert.equals(0, event.argument)
            local stream = engine.createStream()
            event:writeStream(stream, connection)

            local received = VehicleSyncRequestEvent.emptyNew()
            received:readStream(stream, connection)
            assert.equals(follower, received.vehicle)
            assert.equals(ACTION.TOGGLE_CONNECT, received.action)
            assert.equals(STATE.CONNECTED, follower:vsGetState())
            assert.equals(leader, follower:vsGetLeader())
        end)
        it("is ignored when it arrives from the server connection", function()
            local leader, follower = V.createScene()
            leader:vsSetNetworkEnabled(true)
            local event = VehicleSyncRequestEvent.new(follower, ACTION.TOGGLE_CONNECT, 0)
            event:run(engine.createConnection(true))
            assert.equals(STATE.IDLE, follower:vsGetState())
        end)
        it("ignores unknown vehicles", function()
            local event = VehicleSyncRequestEvent.new(nil, ACTION.TOGGLE_CONNECT, 0)
            assert.has_no_error(function() event:run(engine.createConnection(false)) end)
        end)
        it("carries the nudge direction", function()
            local event = VehicleSyncRequestEvent.new({ networkId = 3 }, ACTION.NUDGE, VehicleSyncController.NUDGE.BACK)
            local stream = engine.createStream()
            event:writeStream(stream, nil)
            assert.equals(VehicleSyncController.NUDGE.BACK, stream.data[3])
        end)
    end)

    describe("VehicleSyncStateEvent", function()
        it("round trips a full state onto the client copy", function()
            local leader = V.create({ name = "Harvester", networkId = 50, hasPipe = true })
            local follower = V.create({ name = "Tractor", networkId = 51 })
            local clientLeader = V.create({ name = "Harvester", networkId = 50, side = "client", isServer = false })
            local clientFollower = V.create({ name = "Tractor", networkId = 51, side = "client", isServer = false })

            local event = VehicleSyncStateEvent.new(follower, STATE.TRACKING, leader, { x = 7.5, z = 1.25 }, false, false, REASON.ENGAGED)
            local stream = engine.createStream()
            event:writeStream(stream, nil)

            NetworkUtil.side = "client"
            VehicleSyncStateEvent.emptyNew():readStream(stream, engine.createConnection(true))
            NetworkUtil.side = "server"

            assert.equals(STATE.TRACKING, clientFollower:vsGetState())
            assert.equals(clientLeader, clientFollower:vsGetLeader())
            assert.near(7.5, clientFollower:vsGetHome().x)
            assert.near(1.25, clientFollower:vsGetHome().z)
            assert.is_false(VehicleSyncSpec.getSpec(clientFollower).homeIsAuto)
            assert.is_true(VehicleSyncSpec.getSpec(clientLeader).followers[clientFollower])
        end)
        it("resolves a leader the client does not know yet later", function()
            local leader = V.create({ name = "Harvester", networkId = 52, hasPipe = true })
            local follower = V.create({ name = "Tractor", networkId = 53 })
            local clientFollower = V.create({ name = "Tractor", networkId = 53, side = "client", isServer = false })

            local stream = engine.createStream()
            VehicleSyncStateEvent.new(follower, STATE.CONNECTED, leader, nil, true, false, REASON.CONNECTED):writeStream(stream, nil)
            NetworkUtil.side = "client"
            VehicleSyncStateEvent.emptyNew():readStream(stream, engine.createConnection(true))
            local clientSpec = VehicleSyncSpec.getSpec(clientFollower)
            assert.equals(STATE.CONNECTED, clientSpec.state)
            assert.is_nil(clientSpec.leader)
            assert.equals(52, clientSpec.pendingLeaderId)

            local clientLeader = V.create({ name = "Harvester", networkId = 52, side = "client", isServer = false })
            clientFollower:onUpdate(16, false, false, false)
            NetworkUtil.side = "server"
            assert.equals(clientLeader, clientSpec.leader)
            assert.is_true(VehicleSyncSpec.getSpec(clientLeader).followers[clientFollower])
        end)
        it("round trips an idle state without leader and home", function()
            local vehicle = V.create({ networkId = 60 })
            local clientVehicle = V.create({ networkId = 60, side = "client", isServer = false, entered = true })
            local event = VehicleSyncStateEvent.new(vehicle, STATE.IDLE, nil, nil, true, true, nil)
            assert.equals(REASON.NONE, event.reason)
            local stream = engine.createStream()
            event:writeStream(stream, nil)
            NetworkUtil.side = "client"
            VehicleSyncStateEvent.emptyNew():readStream(stream, engine.createConnection(true))
            NetworkUtil.side = "server"
            assert.equals(STATE.IDLE, clientVehicle:vsGetState())
            assert.is_nil(clientVehicle:vsGetHome())
            assert.is_true(clientVehicle:vsGetNetworkEnabled())
            -- the entered operator of the leader is told that the network opened
            assert.contains(g_currentMission.notifications, "Sync network opened")
        end)
        it("shows feedback without changing state", function()
            local vehicle = V.create({ networkId = 70, entered = true })
            local clientVehicle = V.create({ networkId = 70, side = "client", isServer = false, entered = true })
            local stream = engine.createStream()
            VehicleSyncStateEvent.newFeedback(vehicle, REASON.NOT_IN_ZONE):writeStream(stream, nil)
            NetworkUtil.side = "client"
            VehicleSyncStateEvent.emptyNew():readStream(stream, engine.createConnection(true))
            NetworkUtil.side = "server"
            assert.equals(STATE.IDLE, clientVehicle:vsGetState())
            assert.contains(g_currentMission.warnings, "Not in the operational zone of the harvester")
        end)
        it("is rejected from a client connection and for unknown vehicles", function()
            local vehicle = V.create({})
            local event = VehicleSyncStateEvent.new(vehicle, STATE.CONNECTED, nil, nil, true, false, REASON.CONNECTED)
            event:run(engine.createConnection(false))
            assert.equals(STATE.IDLE, vehicle:vsGetState())
            event = VehicleSyncStateEvent.new({}, STATE.CONNECTED, nil, nil, true, false, REASON.CONNECTED)
            assert.has_no_error(function() event:run(engine.createConnection(true)) end)
            event = VehicleSyncStateEvent.new(nil, STATE.CONNECTED, nil, nil, true, false, REASON.CONNECTED)
            assert.has_no_error(function() event:run(engine.createConnection(true)) end)
        end)
    end)
end)
